import { Link } from "@inertiajs/react";

type PageLink = { url: string | null; label: string; active: boolean };

export default function Pagination({ links }: { links: PageLink[] }) {
    // A single page still has Previous, 1, and Next, so hide anything with no real pages to move between
    if (links.length <= 3) {
        return null;
    }

    return (
        <nav className="mt-8 flex flex-wrap justify-center gap-2" aria-label="Pagination">
            {links.map((link, index) =>
                link.url ? (
                    <Link
                        key={index}
                        href={link.url}
                        preserveScroll
                        className={`btn btn-sm ${link.active ? "btn-primary" : "btn-outline"}`}
                        // Laravel labels contain HTML entities such as &laquo;, generated by the server
                        dangerouslySetInnerHTML={{ __html: link.label }}
                    />
                ) : (
                    <span
                        key={index}
                        className="btn btn-sm btn-disabled"
                        dangerouslySetInnerHTML={{ __html: link.label }}
                    />
                ),
            )}
        </nav>
    );
}
